 status text NOT NULL DEFAULT 'POSTING' CHECK(status IN('POSTING','POSTED')),
 actor text NOT NULL,
 order_line_count integer NOT NULL DEFAULT 0 CHECK(order_line_count>=0),
 recipe_line_count integer NOT NULL DEFAULT 0 CHECK(recipe_line_count>=0),
 skipped_line_count integer NOT NULL DEFAULT 0 CHECK(skipped_line_count>=0),
 movement_count integer NOT NULL DEFAULT 0 CHECK(movement_count>=0),
 total_quantity_kg numeric(14,3) NOT NULL DEFAULT 0 CHECK(total_quantity_kg>=0),
 details jsonb NOT NULL DEFAULT '{}'::jsonb,
 created_at timestamptz NOT NULL DEFAULT now(),
 posted_at timestamptz,
 CONSTRAINT ingredient_consumption_batch_order_unique UNIQUE(pedido_id)
