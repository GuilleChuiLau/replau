CREATE TABLE IF NOT EXISTS api.inventory_stock_controls(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 warehouse_id integer NOT NULL REFERENCES api.almacenes(id) ON DELETE RESTRICT,
 product_id integer NOT NULL REFERENCES api.productos(id) ON DELETE RESTRICT,
 enforcement_enabled boolean NOT NULL DEFAULT false,
 safety_stock numeric(14,3) NOT NULL DEFAULT 0 CHECK(safety_stock>=0),
 reservation_ttl_minutes integer NOT NULL DEFAULT 120 CHECK(reservation_ttl_minutes BETWEEN 15 AND 10080),
 configured_by text NOT NULL,
 notes text,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT inventory_stock_control_unique UNIQUE(warehouse_id,product_id)
);

CREATE TABLE IF NOT EXISTS api.inventory_stock_control_events(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 control_id bigint NOT NULL REFERENCES api.inventory_stock_controls(id) ON DELETE RESTRICT,
 event_type text NOT NULL,
 actor text NOT NULL,
 details jsonb NOT NULL DEFAULT '{}'::jsonb,
 created_at timestamptz NOT NULL DEFAULT now()
);

